type LocalIconName = keyof typeof LOCAL_STROKES;
export type MdmIconName = IconName | LocalIconName;

function isLocal(name: MdmIconName): name is LocalIconName {
  return Object.hasOwn(LOCAL_STROKES, name);
}

interface Props extends Omit<ComponentPropsWithoutRef<'svg'>, 'children'> {
  readonly name: MdmIconName;
}

/** Decorativo (`aria-hidden`): el significado va siempre en el texto. */
export function MdmIcon({ name, className, ...rest }: Props) {
  if (!isLocal(name)) return <Icon name={name} className={className} {...rest} />;
  return (
    <svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" focusable="false" className={joinClasses('size-6 shrink-0', className)} {...rest}>
      <path d={LOCAL_STROKES[name]} />
    </svg>
  );
}
